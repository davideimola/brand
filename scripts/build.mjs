// Builds everything in dist/ and assets/ from tokens/tokens.json and
// src/geometry.mjs. No dependencies: run with `node scripts/build.mjs`.
// PNG exports use @resvg/resvg-js (dev dependency): run `pnpm install` first.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Resvg } from "@resvg/resvg-js";
import {
  MARK_VIEWBOX,
  markCuts,
  WORDMARK_STROKE,
  WORDMARK_VIEWBOX,
  wordmarkKnots,
  wordmarkStrokes,
} from "../src/geometry.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(ROOT, "tokens/tokens.json"), "utf8"));

const out = (path, content) => {
  const full = join(ROOT, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content);
};

// ---------- token resolution ----------

const lookup = (path) => path.split(".").reduce((node, key) => node?.[key], tokens);

const resolve = (value) => {
  if (typeof value === "string") {
    const ref = value.match(/^\{(.+)\}$/);
    if (ref) {
      const target = lookup(ref[1]);
      if (!target) throw new Error(`Unknown token reference ${value}`);
      return resolve(target.$value);
    }
  }
  return value;
};

const leaves = (node, prefix = []) =>
  Object.entries(node)
    .filter(([key]) => !key.startsWith("$"))
    .flatMap(([key, child]) =>
      child && typeof child === "object" && "$value" in child
        ? [[[...prefix, key], resolve(child.$value)]]
        : child && typeof child === "object"
          ? leaves(child, [...prefix, key])
          : [],
    );

const cssValue = (value) =>
  Array.isArray(value)
    ? value.map((v) => (/\s/.test(v) ? `"${v}"` : v)).join(", ")
    : String(value);

const palette = Object.fromEntries(
  leaves(tokens.color.palette).map(([path, value]) => [path.join("-"), value]),
);
const semantic = (mode) =>
  leaves(tokens.color[mode]).map(([path, value]) => [path.join("-"), value]);

const scalarGroups = ["font", "type", "marker", "tape", "radius", "mark", "slides"];
const scalars = scalarGroups.flatMap((group) =>
  leaves(tokens[group]).map(([path, value]) => [`${group}-${path.join("-")}`, value]),
);

// ---------- CSS ----------

const decl = (entries, indent = "  ") =>
  entries.map(([name, value]) => `${indent}--di-${name}: ${cssValue(value)};`).join("\n");

const header = "/* Generated by scripts/build.mjs from tokens/tokens.json. Do not edit. */\n";

const tokensCss = `${header}
:root {
${decl(Object.entries(palette).map(([k, v]) => [`color-${k}`, v]))}

${decl(semantic("light"))}

${decl(scalars)}
}

/* Dark theme: explicit opt-in with data-theme="dark" or .dark, or the
   system preference unless the page pins data-theme="light". */
[data-theme="dark"],
.dark {
${decl(semantic("dark"))}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${decl(semantic("dark"), "    ")}
  }
}

/* Paper is always light: print uses the light ground whatever the theme. */
@media print {
  :root,
  :root:not([data-theme="light"]),
  [data-theme="dark"],
  .dark {
${decl(semantic("light"), "    ")}
  }
}
`;

const tailwindCss = `${header}
@import "./tokens.css";

@theme inline {
${semantic("light")
  .map(([name]) => `  --color-${name}: var(--di-${name});`)
  .join("\n")}
  --color-akane: var(--di-color-akane);

  --font-sans: var(--di-font-family-sans);
  --font-mono: var(--di-font-family-mono);
  --font-label: var(--di-font-family-label);

  --radius-sm: var(--di-radius-sm);
  --radius-md: var(--di-radius-md);
}
`;

out("dist/css/tokens.css", tokensCss);
out("dist/css/tailwind.css", tailwindCss);

const flat = {
  color: {
    palette,
    light: Object.fromEntries(semantic("light")),
    dark: Object.fromEntries(semantic("dark")),
  },
  ...Object.fromEntries(scalars),
};
out("dist/tokens.json", `${JSON.stringify(flat, null, 2)}\n`);

// The drawing module ships as written: pure, no tokens to resolve.
for (const [from, to] of [
  ["src/draw.mjs", "dist/draw.mjs"],
  ["src/draw.d.mts", "dist/draw.d.mts"],
  ["src/draw.css", "dist/css/draw.css"],
]) {
  out(to, readFileSync(join(ROOT, from), "utf8"));
}
out(
  "dist/tokens.mjs",
  `// Generated by scripts/build.mjs. Do not edit.\nexport const tokens = ${JSON.stringify(flat, null, 2)};\nexport default tokens;\n`,
);

// ---------- SVG ----------

const ink = { light: palette.ink, dark: palette.chalk, mono: "currentColor" };
const red = { light: palette.akane, dark: palette["akane-night"], mono: "currentColor" };

const markBody = (cut, fg, knot) => {
  const c = markCuts[cut];
  const stroke = `fill="none" stroke="${fg}" stroke-width="${c.stroke}" stroke-linecap="round"`;
  return [
    `<path d="${c.i}" ${stroke}/>`,
    `<path d="${c.stem}" ${stroke}/>`,
    `<circle cx="${c.bowl.cx}" cy="${c.bowl.cy}" r="${c.bowl.r}" ${stroke}/>`,
    c.tail
      ? `<path d="${c.tail.d}" fill="none" stroke="${fg}" stroke-width="${c.tail.width}" stroke-linecap="round"/>`
      : "",
    `<rect x="${c.knot.x}" y="${c.knot.y}" width="${c.knot.w}" height="${c.knot.h}" rx="${c.knot.rx}" fill="${knot}" transform="rotate(${c.knot.rotate})"/>`,
  ]
    .filter(Boolean)
    .join("");
};

const wordmarkBody = (weight, fg, knot) => {
  const sw = WORDMARK_STROKE[weight];
  const lift = weight === "bold" ? ' transform="translate(0 -3)"' : "";
  const strokes = wordmarkStrokes
    .map((s) =>
      s.circle
        ? `<circle cx="${s.circle.cx}" cy="${s.circle.cy}" r="${s.circle.r}"/>`
        : `<path d="${s.d}"/>`,
    )
    .join("");
  const knots = wordmarkKnots
    .map(
      (k) =>
        `<rect x="${k.x}" y="${k.y}" width="${k.w}" height="${k.h}" rx="${k.rx}" transform="rotate(${k.rotate})"/>`,
    )
    .join("");
  return `<g fill="none" stroke="${fg}" stroke-width="${sw}" stroke-linecap="round" stroke-linejoin="round">${strokes}</g><g fill="${knot}"${lift}>${knots}</g>`;
};

const svg = (viewBox, body, label, size = "") =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"${size} role="img" aria-label="${label}"><title>${label}</title>${body}</svg>\n`;

const vbSize = (vb) => vb.split(" ").map(Number);

for (const cut of ["l", "m", "s"]) {
  for (const mode of ["light", "dark", "mono"]) {
    const suffix = mode === "light" ? "" : `-${mode}`;
    out(
      `assets/svg/mark-${cut}${suffix}.svg`,
      svg(MARK_VIEWBOX, markBody(cut, ink[mode], red[mode]), "Davide Imola"),
    );
  }
}

for (const weight of ["regular", "bold"]) {
  for (const mode of ["light", "dark", "mono"]) {
    const suffix = mode === "light" ? "" : `-${mode}`;
    const name = weight === "regular" ? "wordmark" : "wordmark-bold";
    out(
      `assets/svg/${name}${suffix}.svg`,
      svg(WORDMARK_VIEWBOX[weight], wordmarkBody(weight, ink[mode], red[mode]), "davide imola"),
    );
  }
}

// Lockups: mark beside the wordmark. The mark box is 200 units and is
// scaled so its height is ~1.35 times the wordmark's ascender height.
const lockup = (cut, weight, mode) => {
  const [wx, wy, ww, wh] = vbSize(WORDMARK_VIEWBOX[weight]);
  const markSize = 168;
  const gap = cut === "s" ? 18 : 28;
  const wordY = (markSize - wh) / 2 + 8;
  const width = markSize + gap + ww + 12;
  const body = `<svg x="0" y="0" width="${markSize}" height="${markSize}" viewBox="${MARK_VIEWBOX}">${markBody(cut, ink[mode], red[mode])}</svg><svg x="${markSize + gap}" y="${wordY}" width="${ww}" height="${wh}" viewBox="${wx} ${wy} ${ww} ${wh}">${wordmarkBody(weight, ink[mode], red[mode])}</svg>`;
  return svg(`0 0 ${width} ${markSize}`, body, "Davide Imola");
};

for (const mode of ["light", "dark", "mono"]) {
  const suffix = mode === "light" ? "" : `-${mode}`;
  out(`assets/svg/lockup${suffix}.svg`, lockup("l", "regular", mode));
  out(`assets/svg/lockup-small${suffix}.svg`, lockup("s", "bold", mode));
}

// Favicon: the small cut, switching ink with the browser theme.
out(
  "assets/svg/favicon.svg",
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${MARK_VIEWBOX}"><style>.i{stroke:${palette.ink}}.k{fill:${palette.akane}}@media (prefers-color-scheme: dark){.i{stroke:${palette.chalk}}.k{fill:${palette["akane-night"]}}}</style>${markBody("s", "#000", "#000")
    .replace(/stroke="#000"/g, 'class="i"')
    .replace(/fill="#000"/g, 'class="k"')}</svg>\n`,
);

// Avatar: ink disc, chalk mark, red knot. Safe for circular crops.
out(
  "assets/svg/avatar.svg",
  svg(
    "0 0 200 200",
    `<rect width="200" height="200" fill="${palette.ink}"/><g transform="translate(24 30) scale(0.66)">${markBody("m", palette.paper, palette["akane-night"])}</g>`,
    "Davide Imola",
  ),
);

// ---------- README images ----------
// Showcase images for the README (no text inside: GitHub renders SVG
// without web fonts, so every label lives in the Markdown).

const cutsRow = (mode) => {
  const sizes = [["l", 200], ["m", 96], ["s", 40]];
  let x = 0;
  const parts = sizes.map(([cut, size]) => {
    const part = `<svg x="${x}" y="${200 - size}" width="${size}" height="${size}" viewBox="${MARK_VIEWBOX}">${markBody(cut, ink[mode], red[mode])}</svg>`;
    x += size + 64;
    return part;
  });
  return svg(`0 0 ${x - 64} 200`, parts.join(""), "The mark in its three cuts: L, M and S");
};
out("docs/images/cuts.svg", cutsRow("light"));
out("docs/images/cuts-dark.svg", cutsRow("dark"));

const swatches = [
  palette.paper, palette.ink, palette.akane, palette.slate, palette.night, palette.chalk,
];
out(
  "docs/images/palette.svg",
  svg(
    `0 0 ${swatches.length * 120} 120`,
    swatches
      .map((c, i) => `<rect x="${i * 120}" y="0" width="120" height="120" fill="${c}"/>`)
      .join("") + `<rect x="0.5" y="0.5" width="119" height="119" fill="none" stroke="${palette.rule}"/>`,
    "Palette: paper, ink, akane, slate, night, chalk",
  ),
);

// ---------- PNG ----------

const pngs = [
  ["mark-l.svg", "mark-l-1024.png", 1024],
  ["mark-l-dark.svg", "mark-l-dark-1024.png", 1024],
  ["avatar.svg", "avatar-512.png", 512],
  ["avatar.svg", "avatar-1024.png", 1024],
  ["mark-s.svg", "favicon-32.png", 32],
  ["avatar.svg", "apple-touch-icon-180.png", 180],
  ["lockup.svg", "lockup-1200.png", 1200],
  ["lockup-dark.svg", "lockup-dark-1200.png", 1200],
];

for (const [from, to, width] of pngs) {
  const source = readFileSync(join(ROOT, "assets/svg", from), "utf8");
  const png = new Resvg(source, { fitTo: { mode: "width", value: width } }).render().asPng();
  out(`assets/png/${to}`, png);
}
console.log(`PNG: ${pngs.length} files`);

console.log("Built dist/ and assets/svg/");
